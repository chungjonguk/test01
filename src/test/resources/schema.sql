-- H2(MODE=MySQL + DATABASE_TO_LOWER) 테스트 스키마 — 운영 user/biz_company 컬럼과 맞춤

CREATE TABLE IF NOT EXISTS "user" (
    id          VARCHAR(100) NOT NULL PRIMARY KEY,
    pw          VARCHAR(100) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    sex         VARCHAR(100) NOT NULL,
    rrno        VARCHAR(255) NOT NULL,
    email          VARCHAR(100) NOT NULL UNIQUE,
    zipcode        VARCHAR(10),
    address        VARCHAR(255),
    address_detail VARCHAR(255),
    profile_image_url VARCHAR(500),
    cover_image_url VARCHAR(500),
    home_zipcode VARCHAR(10),
    home_address VARCHAR(255),
    home_address_detail VARCHAR(255),
    home_phone VARCHAR(30),
    work_zipcode VARCHAR(10),
    work_address VARCHAR(255),
    work_address_detail VARCHAR(255),
    work_phone VARCHAR(30),
    work_company_name VARCHAR(200),
    primary_address_type VARCHAR(20),
    update_id   VARCHAR(100) NOT NULL,
    reg_dt      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    upd_dt      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS biz_company (
  company_id    BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  company_nm    VARCHAR(200)  NOT NULL,
  biz_no        VARCHAR(20)   NULL,
  ceo_nm        VARCHAR(100)  NULL,
  tel           VARCHAR(30)   NULL,
  email         VARCHAR(200)  NULL,
  address       VARCHAR(500)  NULL,
  status_cd     VARCHAR(30)   NOT NULL DEFAULT 'ACTIVE',
  use_yn        CHAR(1)       NOT NULL DEFAULT 'Y',
  memo          VARCHAR(1000) NULL,
  reg_id        VARCHAR(100)  NOT NULL DEFAULT 'SYSTEM',
  reg_dt        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_id     VARCHAR(100)  NOT NULL DEFAULT 'SYSTEM',
  update_dt     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (company_id)
);
